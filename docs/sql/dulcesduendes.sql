-- ==========================================
-- 6. ACTUALIZAR SALDOS (MONTO) EN CLIENTES
-- ==========================================
-- Actualiza los saldos deudores reales calculando la suma de los pagos 'Pendiente' de cada cliente.

UPDATE clientes c
LEFT JOIN (
    SELECT ClienteId, SUM(Monto) AS TotalPendiente
    FROM pagos
    WHERE Estado = 'Pendiente'
    GROUP BY ClienteId
) p ON c.Id = p.ClienteId
SET c.Monto = COALESCE(p.TotalPendiente, 0.00);